#!/usr/bin/env python3
"""IMPERIUM procedural art generator (entry point).

Usage:  python3 tools/assets/gen_art.py [group ...]
Groups: parchment vignette menu loading events badges ui icons   (default: all)
All art is original and generated by code (Pillow + numpy). See docs/ART_ASSETS.md.
"""
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import art_backgrounds as bg  # noqa: E402


def groups():
    g = {
        "parchment": [bg.render_parchment],
        "vignette": [bg.render_vignette],
        "menu": [bg.render_menu_bg],
        "loading": [bg.loading_1, bg.loading_2, bg.loading_3, bg.loading_4],
    }
    try:
        import art_events as ev
        g["events"] = [ev.render_all]
    except ImportError:
        pass
    try:
        import art_ui as ui
        g["badges"] = [ui.render_badges]
        g["ui"] = [ui.render_ui]
        g["icons"] = [ui.render_icons]
    except ImportError:
        pass
    return g


def main(argv):
    g = groups()
    want = argv[1:] or list(g)
    for name in want:
        t = time.time()
        print(f"[{name}]")
        for fn in g[name]:
            fn()
        print(f"  ({time.time() - t:.1f}s)")


if __name__ == "__main__":
    main(sys.argv)
